export function detectZone(x: number, y: number): string {
  // Left corridor & stairs
  if (x >= 28 && x <= 100 && y >= 68 && y <= 530) {
    if (y >= 470) return 'บันไดหนีไฟ';
    return 'ทางเดินระเบียงฝั่งซ้าย';
  }

  // Top Left: ห้องเก็บสารเคมี (Cyan)
  if (x >= 165 && x <= 275 && y >= 70 && y <= 180) {
    return 'ห้องเก็บสารเคมี';
  }

  // Mid Left: ห้องเครื่องชั่งน้ำหนักผ้า (Peach/Pink)
  if (x >= 165 && x <= 275 && y > 180 && y <= 310) {
    return 'ห้องเครื่องชั่งน้ำหนักผ้า';
  }

  // Hallway between rooms
  if (x >= 165 && x <= 275 && y > 310 && y <= 400) {
    return 'โถงทางเดินกลาง';
  }

  // Bottom Left: ห้องควบคุม (Orange)
  if (x >= 165 && x <= 265 && y > 400 && y <= 530) {
    return 'ห้องควบคุม';
  }

  // Center top & upper pink: ห้องเครื่องซักผ้า (Pink with washers)
  if (x >= 275 && x <= 595 && y >= 180 && y <= 310) {
    return 'ห้องเครื่องซักผ้า';
  }

  // Center middle: ห้องเครื่องอบผ้า (Green with dryers)
  if (x >= 275 && x <= 595 && y > 310 && y <= 400) {
    return 'ห้องเครื่องอบผ้า';
  }

  // Center bottom: จัดเตรียม / ซ่อมบำรุงผ้า
  if (x >= 275 && x <= 515 && y > 400 && y <= 530) {
    if (x <= 440) return 'ห้องเก็บอุปกรณ์และจัดเตรียมผ้า';
    return 'พื้นที่คัดแยกผ้า';
  }

  // Meeting Room: ห้องประชุม (Gray)
  if (x >= 515 && x <= 595 && y > 400 && y <= 530) {
    return 'ห้องประชุม';
  }

  // Office Room: ห้องสำนักงาน (Mint Green)
  if (x >= 595 && x <= 705 && y > 400 && y <= 530) {
    return 'ห้องสำนักงาน';
  }

  // Packing Room: ห้องบรรจุผ้า (Lavender Purple)
  if (x >= 705 && x <= 885 && y > 400 && y <= 530) {
    return 'ห้องบรรจุผ้า';
  }

  // Ironing & Folding Machine Area (Purple-Gray)
  if (x >= 595 && x <= 705 && y >= 175 && y <= 310) {
    return 'บริเวณเครื่องรีดผ้าและเครื่องพับผ้า';
  }

  // Top right linen hall: ห้องพับผ้า (Light blue / white large hall)
  if (x >= 595 && x <= 885 && y >= 70 && y <= 400) {
    return 'ห้องพับผ้า';
  }

  // Bottom loading dock
  if (y > 530 && y <= 590 && x >= 28 && x <= 885) {
    return 'ชานชาลารับ-ส่งผ้า (Loading Dock)';
  }

  return 'โถงทางเดินและพื้นที่ส่วนกลาง';
}
